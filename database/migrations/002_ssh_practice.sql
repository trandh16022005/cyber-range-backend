BEGIN;
SET LOCAL search_path TO public, pg_catalog;

CREATE TABLE IF NOT EXISTS ssh_practice_runs (
    id UUID PRIMARY KEY,
    lab_session_id UUID NOT NULL REFERENCES ssh_lab_sessions(id),
    exercise_id BIGINT NOT NULL REFERENCES exercises(id),
    assessment_id BIGINT NOT NULL REFERENCES assessments(id),
    red_team_id BIGINT NOT NULL REFERENCES teams(id),
    blue_team_id BIGINT NOT NULL REFERENCES teams(id),
    scenario_version INTEGER NOT NULL DEFAULT 1 CHECK (scenario_version > 0),
    state VARCHAR(20) NOT NULL CHECK (state IN ('APPROVED', 'ACTIVE', 'PROPOSED', 'RECOVERY', 'SUBMITTED', 'REVIEWED')),
    connection_status VARCHAR(16) NOT NULL DEFAULT 'NONE'
        CHECK (connection_status IN ('NONE', 'QUEUED', 'CHECKING', 'SUCCEEDED', 'FAILED')),
    connection_at TIMESTAMPTZ,
    submission JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(submission) = 'object'),
    score INTEGER CHECK (score BETWEEN 0 AND 100),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (lab_session_id),
    CHECK (red_team_id <> blue_team_id)
);

CREATE INDEX IF NOT EXISTS idx_ssh_practice_exercise ON ssh_practice_runs (exercise_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS ssh_practice_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES ssh_practice_runs(id),
    actor_id BIGINT REFERENCES users(id),
    action VARCHAR(32) NOT NULL,
    detail TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS idx_ssh_practice_history_run ON ssh_practice_history (run_id, id);
COMMIT;
